/* Fallback for champions not in the table: map Riot's class tags to lanes. */
window.guessRoles = function guessRoles(tags) {
  const byTag = {
    Marksman: ["bot"],
    Support: ["support"],
    Mage: ["mid"],
    Assassin: ["mid", "jungle"],
    Fighter: ["top", "jungle"],
    Tank: ["top", "support"],
  };
  const roles = new Set();
  (tags || []).forEach((t) => (byTag[t] || []).forEach((r) => roles.add(r)));
  return roles.size ? [...roles] : ["mid"];
};
